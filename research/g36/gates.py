    print("The historical period is generated by identical parameters in every regime. A backtest")
    print("cannot distinguish them; only the pilot can.")
    print("\n%-28s %12s %12s %14s %12s %10s" % (
        "regime", "holdout_RMSE", "holdout_R2", "mean_hist_load", "TRUTH", "decision"))
    for sp, w, t, e in rows:
        h = historical_metrics(w)
        print("%-28s %12.4f %12.4f %14.4f %12.4f %10s" % (
            sp.name, h["holdout_rmse"], h["holdout_r2"], h["mean_hist_load"],
            t["target_peak_mean"], t["decision"]))
    print("\nThe discriminating pair is hidden_b_flat_in_heat and hidden_c_fades_in_heat:")
    b = [r for r in rows if r[0].name.startswith("hidden_b")][0]
    c = [r for r in rows if r[0].name.startswith("hidden_c")][0]
    hb, hc = historical_metrics(b[1]), historical_metrics(c[1])
    print("   identical response magnitude, identical history generation")
    print("   holdout RMSE  %.4f vs %.4f   (difference %.4f)" % (
        hb["holdout_rmse"], hc["holdout_rmse"], abs(hb["holdout_rmse"] - hc["holdout_rmse"])))
    print("   TRUTH         %.4f vs %.4f   -> %s vs %s" % (
        b[2]["target_peak_mean"], c[2]["target_peak_mean"], b[2]["decision"], c[2]["decision"]))

    print()
    print("=" * 104)
    print("RECOGNITION-VS-EXECUTION GATE  (the gate G35 failed)")
    print("=" * 104)
    valid_sd = 0.0142     # measured: sampling sd of the accepted estimator
    print("Each row hands the analyst an insight FOR FREE and reports the best analysis that")
    print("insight alone supports. Errors in units of the accepted estimator's sampling sd (%.4f).\n"
          % valid_sd)
    print("%-44s %s  %s" % ("insight given away", "".join("%11s" % n[:10] for n in names), "worst"))
    for hint, keys in HINTS.items():
        best_per_regime = []
        for i, (sp, w, t, e) in enumerate(rows):
            errs = [abs(e[k] - t["target_peak_mean"]) for k in keys if k in e]
            best_per_regime.append(min(errs))
        worst = max(best_per_regime)
        line = "".join("%11.1f" % (v / valid_sd) for v in best_per_regime)
        print("%-44s %s  %5.1f sd" % (hint, line, worst / valid_sd))
    print("\nwrong DECISIONS remaining after each insight:")
    for hint, keys in HINTS.items():
        bad = 0
        for sp, w, t, e in rows:
            k = keys[0]
            d = "procure" if e[k] >= sp.capacity_gate else "defer"
            if d != t["decision"]:
                bad += 1
        print("   %-44s %d / %d regimes wrong" % (hint, bad, len(rows)))

    print()
    print("=" * 104)
    print("COHERENT-BUT-WRONG GATE")
    print("=" * 104)
    print("W1_historical_only IS the incumbent model. Its backtest is excellent by construction;")
    print("it reconciles, calibrates and validates perfectly on every historical summer, and it is")
    print("wrong about the future because the mechanism it omits did not exist in the past.\n")
    print("%-28s %12s %12s %12s %12s" % ("regime", "holdout_R2", "forecast", "truth", "error"))
    for sp, w, t, e in rows:
        h = historical_metrics(w)
