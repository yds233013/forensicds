# ----------------------------------------------------------------- same history / different future
def historical_metrics(w):
    """Fit the historical model on summers 1-2 and score it on summer 3. This is the backtest a
    professional team would run, and it is the number that makes a wrong analysis look safe."""
    seg = w["seg"]
    train, test = w["hist"][:-1], w["hist"][-1]
    coef = {}
    for s in range(4):
        m = seg == s
        xs, ys = [], []
        for h in train:
            xs.append(np.repeat(h["cdd"], m.sum()))
            ys.append(h["load"][m].T.ravel())
        x = np.concatenate(xs); y = np.concatenate(ys)
        A = np.column_stack([np.ones_like(x), x])
        coef[s] = np.linalg.lstsq(A, y, rcond=None)[0]
    errs, ys = [], []
    for s in range(4):
        m = seg == s
        a, b = coef[s]
        pred = a + b * test["cdd"][None, :]
        errs.append((test["load"][m] - pred).ravel())
        ys.append(test["load"][m].ravel())
    e = np.concatenate(errs); y = np.concatenate(ys)
    rmse = float(np.sqrt(np.mean(e ** 2)))
    r2 = float(1 - np.mean(e ** 2) / np.var(y))
    return dict(holdout_rmse=rmse, holdout_r2=r2, mean_hist_load=float(
        np.mean([h["load"].mean() for h in w["hist"]])))


# --------------------------------------------------------------------------------- cheap solves
def cheap_solves(w, e, t):
    sp = w["spec"]
    hist_mean = float(np.mean([h["load"].mean() for h in w["hist"]]))
    out = {
        "C1_historical_model_output": e["W1_historical_only"],
        "C3_last_value": float(w["hist"][-1]["load"].mean()),
        "C4_seasonal_naive": hist_mean,
        "C6_historical_mean": hist_mean,
        "C7_pilot_mean": float(w["pilot_load"][w["tou"]].mean()),
        "C9_constant_procure": 1e9,
        "C10_constant_defer": -1e9,
        "C11_largest_segment_only": None,
        "C13_latest_period": float(w["hist"][-1]["load"].mean()),
        "C15_intervention_flag": None,
        "C17_aggregate_pre_post": None,
        "C24_linear_extrapolation": None,
    }
    # largest segment only: forecast built from the single biggest segment
    stable = _fit_stable(w)
    big = int(np.argmax(_seg_shares(w)))
    a, b = stable[big]
    out["C11_largest_segment_only"] = float(np.mean(a + b * w["cdd_target"]))
    # intervention flag: historical mean scaled by a flat "policy will cut 10%" rule of thumb
    out["C15_intervention_flag"] = hist_mean * 0.90
    # aggregate pre/post inside the pilot, applied to the historical level
    pre = float(w["pilot_load"][w["optin"] & ~w["tou"]].mean())
    post = float(w["pilot_load"][w["tou"]].mean())
    out["C17_aggregate_pre_post"] = hist_mean * (post / pre)
    # naive linear extrapolation of the historical summer means
    means = [h["load"].mean() for h in w["hist"]]
    slope = (means[-1] - means[0]) / max(len(means) - 1, 1)
    out["C24_linear_extrapolation"] = float(means[-1] + slope)
    return out


